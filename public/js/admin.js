function applyTranslations() {
    document.documentElement.lang = state.language;
    document.documentElement.dir =
        state.language === "ar" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;

        if (translations[state.language][key] !== undefined) {
            element.textContent = translations[state.language][key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const key = element.dataset.i18nPlaceholder;

        if (translations[state.language][key] !== undefined) {
            element.placeholder = translations[state.language][key];
        }
    });

    const languageButton = $("#languageToggle");

    if (languageButton) {
        languageButton.textContent =
            state.language === "ar" ? "EN" : "عربي";

        languageButton.setAttribute("aria-label", t("languageLabel"));
    }

    updateThemeButton();
    updateConnectionStatus();

    renderContacts();
    renderRules();
    renderClinics();
    renderAnalytics();

    const activeLink = $(".nav-link.active");
    const activeTitle = activeLink?.querySelector("[data-i18n]");

    if (activeTitle) {
        setText("#pageTitle", activeTitle.textContent);
    }
}

function updateThemeButton() {
    const button = $("#themeToggle");

    if (!button) {
        return;
    }

    const isDark = document.documentElement.dataset.theme !== "light";

    button.textContent = isDark ? "☼" : "☾";
    button.setAttribute(
        "aria-label",
        isDark ? t("themeDark") : t("themeLight")
    );
    button.title = isDark ? t("themeDark") : t("themeLight");
}

function toggleTheme() {
    const html = document.documentElement;

    html.dataset.theme =
        html.dataset.theme === "light" ? "dark" : "light";

    updateThemeButton();
}

function toggleLanguage() {
    state.language = state.language === "ar" ? "en" : "ar";
    applyTranslations();
}

function showSection(target) {
    const section = document.getElementById(target);

    if (!section || !section.classList.contains("page-section")) {
        return;
    }

    document.querySelectorAll(".page-section").forEach((panel) => {
        panel.hidden = panel.id !== target;
    });

    document.querySelectorAll(".nav-link").forEach((link) => {
        const isActive = link.dataset.target === target;

        link.classList.toggle("active", isActive);

        if (isActive) {
            link.setAttribute("aria-current", "page");
        } else {
            link.removeAttribute("aria-current");
        }
    });

    const activeLink =
        document.querySelector(`.nav-link[data-target="${target}"]`);

    const activeTitle = activeLink?.querySelector("[data-i18n]");

    if (activeTitle) {
        setText("#pageTitle", activeTitle.textContent);
    } else {
        const fallback = {
            dashboard: "dashboard",
            contacts: "contacts",
            clinics: "clinics",
            rules: "rules",
            analytics: "analytics",
            "data-management": "dataManagement"
        };

        setText("#pageTitle", t(fallback[target] ?? "dashboard"));
    }

    closeSidebar();

    if (target === "contacts") {
        loadContacts();
    } else if (target === "clinics") {
        loadClinics();
    } else if (target === "rules") {
        loadRules();
    } else if (target === "analytics") {
        loadAnalytics();
    }
}

function openSidebar() {
    $("#sidebar")?.classList.add("open");
    $("#menuButton")?.setAttribute("aria-expanded", "true");
}

function closeSidebar() {
    $("#sidebar")?.classList.remove("open");
    $("#menuButton")?.setAttribute("aria-expanded", "false");
}

function initializeNavigation() {
    document.querySelectorAll("[data-target]").forEach((link) => {
        link.addEventListener("click", (event) => {
            const target = link.dataset.target;

            if (!target) {
                return;
            }

            event.preventDefault();
            showSection(target);
            history.replaceState(null, "", `#${target}`);
        });
    });

    const initialTarget = window.location.hash.slice(1);
    const initialSection = document.getElementById(initialTarget);

    showSection(
        initialSection?.classList.contains("page-section")
            ? initialTarget
            : "dashboard"
    );

    $("#menuButton")?.addEventListener("click", () => {
        if ($("#sidebar")?.classList.contains("open")) {
            closeSidebar();
        } else {
            openSidebar();
        }
    });

    document.addEventListener("keydown", (event) => {
        if (event.key === "Escape") {
            closeSidebar();
        }
    });
}

