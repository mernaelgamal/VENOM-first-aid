const $ = (selector) => document.querySelector(selector);

function t(key) {
    return translations[state.language][key] ?? key;
}

function setText(selector, value) {
    const element = $(selector);

    if (element) {
        element.textContent = String(value ?? "");
    }
}

function escapeHTML(value) {
    return String(value ?? "").replace(/[&<>"']/g, (character) => ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;"
    })[character]);
}

function getValue(object, keys, fallback = "") {
    if (!object || typeof object !== "object") {
        return fallback;
    }

    for (const key of keys) {
        const value = object[key];

        if (value !== undefined && value !== null && value !== "") {
            return value;
        }
    }

    return fallback;
}

function formatDate(value) {
    if (!value) {
        return t("unknown");
    }

    const date = new Date(value);

    if (Number.isNaN(date.getTime())) {
        return String(value);
    }

    return new Intl.DateTimeFormat(
        state.language === "ar" ? "ar-EG" : "en-GB",
        {
            dateStyle: "medium",
            timeStyle: "short"
        }
    ).format(date);
}

async function fetchJSON(url) {
    const response = await fetch(url, {
        method: "GET",
        headers: { Accept: "application/json" },
        credentials: "same-origin",
        cache: "no-store"
    });

    if (!response.ok) {
        throw new Error(`HTTP ${response.status}`);
    }

    return response.json();
}

async function mutateJSON(url, method, payload) {
    const csrfToken = document.querySelector('meta[name="csrf-token"]')?.content ?? "";
    const response = await fetch(url, {
        method,
        credentials: "same-origin",
        headers: {
            Accept: "application/json",
            "Content-Type": "application/json",
            "X-CSRF-Token": csrfToken
        },
        body: payload === undefined ? undefined : JSON.stringify(payload)
    });
    const data = await response.json().catch(() => ({}));
    if (!response.ok) {
        throw new Error(data.message || `HTTP ${response.status}`);
    }
    return data;
}

function openDialog(dialogId) {
    const dialog = document.getElementById(dialogId);
    if (dialog && typeof dialog.showModal === "function") dialog.showModal();
}

function closeDialog(dialogId) {
    const dialog = document.getElementById(dialogId);
    if (dialog?.open) dialog.close();
}

function fillForm(form, values) {
    Object.entries(values).forEach(([name, value]) => {
        const field = form.elements.namedItem(name);
        if (field) field.value = value ?? "";
    });
}

function getFormObject(form, fields) {
    const formData = new FormData(form);
    return Object.fromEntries(fields.map((field) => [field, String(formData.get(field) ?? "").trim()]));
}

function setDialogError(selector, message = "") {
    const element = $(selector);
    if (element) {
        element.textContent = message;
        element.className = "feedback-message";
        if (message) element.classList.add("error");
    }
}

function setFeedback(selector, message, type = "") {
    const element = $(selector);

    if (!element) {
        return;
    }

    element.textContent = message;
    element.className = "feedback-message";

    if (type) {
        element.classList.add(type);
    }
}

function setTableMessage(selector, columns, message) {
    const body = $(selector);

    if (!body) {
        return;
    }

    const row = document.createElement("tr");
    const cell = document.createElement("td");

    cell.colSpan = columns;
    cell.textContent = message;

    row.appendChild(cell);
    body.replaceChildren(row);
}

function renderContacts() {
    const body = $("#contactsTableBody");
    if (!body) return;

    const search = ($("#contactSearch")?.value ?? "").trim().toLocaleLowerCase();
    const filtered = state.contacts.filter((contact) => {
        const values = [
            getValue(contact, ["name", "full_name", "contact_name"]),
            getValue(contact, ["phone", "phone_number", "mobile"]),
            getValue(contact, ["type", "category", "role"]),
            getValue(contact, ["available_hours", "availability", "hours"]),
            getValue(contact, ["campus_area", "area", "location", "region"])
        ];
        return values.some((value) => String(value).toLocaleLowerCase().includes(search));
    });

    if (!filtered.length) {
        setTableMessage("#contactsTableBody", 6, t("noResults"));
        setText("#contactsCount", `${t("total")}: 0`);
        return;
    }

    body.innerHTML = filtered.map((contact) => {
        const recordId = getValue(contact, ["_record_id"], state.contacts.indexOf(contact));
        return `
            <tr>
                <td>${escapeHTML(getValue(contact, ["name", "full_name", "contact_name"], t("unknown")))}</td>
                <td>${escapeHTML(getValue(contact, ["phone", "phone_number", "mobile"], t("unknown")))}</td>
                <td>${escapeHTML(getValue(contact, ["type", "category", "role"], t("unknown")))}</td>
                <td>${escapeHTML(getValue(contact, ["available_hours", "availability", "hours"], t("unknown")))}</td>
                <td>${escapeHTML(getValue(contact, ["campus_area", "area", "location", "region"], t("unknown")))}</td>
                <td class="row-actions">
                    <button type="button" class="small-action" data-action="edit-contact" data-id="${escapeHTML(recordId)}">${escapeHTML(t("edit"))}</button>
                    <button type="button" class="small-action danger-action" data-action="delete-contact" data-id="${escapeHTML(recordId)}">${escapeHTML(t("delete"))}</button>
                </td>
            </tr>`;
    }).join("");
    setText("#contactsCount", `${t("total")}: ${filtered.length}`);
}

function renderRules() {
    const body = $("#rulesTableBody");
    if (!body) return;

    const search = ($("#ruleSearch")?.value ?? "").trim().toLocaleLowerCase();
    const filtered = state.rules.filter((rule) => {
        if (typeof rule === "string" || typeof rule === "number") {
            return String(rule).toLocaleLowerCase().includes(search);
        }
        const values = [
            getValue(rule, ["id", "rule_id", "identifier", "code"]),
            getValue(rule, ["title", "name", "condition", "topic"]),
            getValue(rule, ["action", "description", "details", "rule", "advice", "response", "treatment"])
        ];
        return values.some((value) => String(value).toLocaleLowerCase().includes(search));
    });

    if (!filtered.length) {
        setTableMessage("#rulesTableBody", 4, t("noResults"));
        setText("#rulesCount", `${t("total")}: 0`);
        return;
    }

    body.innerHTML = filtered.map((rule, index) => {
        if (!rule || typeof rule !== "object") {
            return `<tr><td>${index + 1}</td><td>${escapeHTML(rule)}</td><td>—</td><td>—</td></tr>`;
        }
        const identifier = getValue(rule, ["rule_id", "id", "identifier", "code"], index + 1);
        const title = getValue(rule, ["title", "name", "condition", "topic"], t("unknown"));
        const details = getValue(rule, ["action", "description", "details", "rule", "advice", "response", "treatment"], "—");
        return `
            <tr>
                <td>${escapeHTML(identifier)}</td>
                <td>${escapeHTML(title)}</td>
                <td>${escapeHTML(details)}</td>
                <td class="row-actions">
                    <button type="button" class="small-action" data-action="edit-rule" data-id="${escapeHTML(identifier)}">${escapeHTML(t("edit"))}</button>
                    <button type="button" class="small-action danger-action" data-action="delete-rule" data-id="${escapeHTML(identifier)}">${escapeHTML(t("delete"))}</button>
                </td>
            </tr>`;
    }).join("");
    setText("#rulesCount", `${t("total")}: ${filtered.length}`);
}

