async function handleRuleSubmit(event) {
    event.preventDefault();
    const form = event.currentTarget;
    const ruleId = form.elements.namedItem("rule_id").value.trim();
    const editing = form.elements.namedItem("rule_id").readOnly;
    const payload = getFormObject(form, ["condition", "action", "severity", "referral"]);
    payload.symptom_triggers = String(form.elements.namedItem("symptom_triggers").value || "")
        .split(/\r?\n|,/).map((item) => item.trim()).filter(Boolean);
    if (!editing) payload.rule_id = ruleId;
    try {
        await mutateJSON(editing ? `/api/rules/${encodeURIComponent(ruleId)}` : "/api/rules", editing ? "PUT" : "POST", payload);
        closeDialog("ruleDialog");
        await loadRules();
        setFeedback("#rulesFeedback", t("saved"), "success");
    } catch (error) {
        setDialogError("#ruleDialogFeedback", error.message || t("requestError"));
    }
}

